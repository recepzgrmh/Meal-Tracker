import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const dartRoot = join(root, 'lib')

function filesIn(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name)
    return statSync(path).isDirectory() ? filesIn(path) : path.endsWith('.dart') ? [path] : []
  })
}

function otaCalls(source) {
  const calls = []
  for (let start = source.indexOf('context.ota('); start >= 0; start = source.indexOf('context.ota(', start + 1)) {
    let depth = 0
    let quote = ''
    let escaped = false
    for (let index = start + 'context.ota'.length; index < source.length; index++) {
      const char = source[index]
      if (quote) {
        if (escaped) escaped = false
        else if (char === '\\') escaped = true
        else if (char === quote) quote = ''
        continue
      }
      if (char === "'" || char === '"') quote = char
      else if (char === '(') depth++
      else if (char === ')' && --depth === 0) {
        calls.push(source.slice(start, index + 1))
        break
      }
    }
  }
  return calls
}

function literal(call, field) {
  const pattern = field === 'key'
    ? /^context\.ota\(\s*(['"])((?:\\.|(?!\1).)*)\1/s
    : new RegExp(`${field}:\\s*(['"])((?:\\\\.|(?!\\1).)*)\\1`, 's')
  const match = call.match(pattern)
  return match?.[2]?.replaceAll("\\'", "'").replaceAll('\\"', '"')
}

const rows = new Map()
const trArb = JSON.parse(readFileSync(join(root, 'lib/l10n/app_tr.arb'), 'utf8'))
const enArb = JSON.parse(readFileSync(join(root, 'lib/l10n/app_en.arb'), 'utf8'))
for (const [key, tr] of Object.entries(trArb)) {
  if (!key.startsWith('@') && typeof tr === 'string' && typeof enArb[key] === 'string') {
    rows.set(key, { key, tr, en: enArb[key], source: 'ARB' })
  }
}

for (const file of filesIn(dartRoot)) {
  const source = readFileSync(file, 'utf8')
  for (const call of otaCalls(source)) {
    const key = literal(call, 'key')
    const tr = literal(call, 'tr')
    const en = literal(call, 'en')
    if (key && tr && en) rows.set(key, { key, tr, en, source: relative(root, file) })
  }
}

const catalog = [...rows.values()].sort((left, right) => left.key.localeCompare(right.key))
const output = `// Generated by scripts/generate-mobile-copy-catalog.mjs. Do not edit manually.\nexport const mobileCopyCatalog = ${JSON.stringify(catalog, null, 2)} as const\n`
writeFileSync(join(root, 'admin-dashboard/src/mobileCopyCatalog.generated.ts'), output)
console.log(`Generated ${catalog.length} OTA copy keys.`)
