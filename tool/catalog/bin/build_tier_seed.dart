// Emits a REVIEWABLE, split SQL seed for a catalog tier.
//
//   dart run tool/catalog/bin/build_tier_seed.dart \
//     --manifest tool/catalog/out/catalog_tier_a_manifest.json \
//     --mapping  tool/catalog/data/catalog_tier_a_mapping.json
//
// Nothing here is applied and nothing is invented: every value is copied from
// the manifest, which is built from hashed source snapshots. Output is split
// by table so the reviewable file stays reviewable, and the image PUBLISH block
// is written as .sql.txt so it cannot be applied by accident.
//
// A food whose portion could not be resolved is still written: its composition
// is published and verified, and only its food_portions rows are absent. The
// app asks the user for the amount. A food with no published composition is
// the only kind that is skipped entirely.
import 'dart:convert';
import 'dart:io';

import '../src/hashing.dart';

void main(List<String> args) {
  final manifestPath = _arg(args, '--manifest');
  final mappingPath = _arg(args, '--mapping');
  if (manifestPath == null || mappingPath == null) {
    stderr.writeln(
      'Usage: build_tier_seed.dart --manifest <path> --mapping <path> '
      '[--out-dir <dir>] [--source <name>]',
    );
    exit(64);
  }

  final manifest =
      jsonDecode(File(manifestPath).readAsStringSync()) as Map<String, dynamic>;
  final mapping =
      jsonDecode(File(mappingPath).readAsStringSync()) as Map<String, dynamic>;
  final batchId = manifest['batchId'] as String;
  final source = _arg(args, '--source') ?? 'turkomp-tuber';
  final outDir = _arg(args, '--out-dir') ?? 'supabase/seed/catalog/$batchId';

  final rows = (manifest['portions'] as List).cast<Map<String, dynamic>>();
  final bySlug = <String, List<Map<String, dynamic>>>{};
  for (final row in rows) {
    bySlug.putIfAbsent(row['food_slug'] as String, () => []).add(row);
  }
  final foods = (mapping['foods'] as List).cast<Map<String, dynamic>>();

  final header =
      '-- $batchId — REVIEW REQUIRED, DO NOT APPLY UNREVIEWED.\n'
      '--\n'
      '-- Generated by tool/catalog/bin/build_tier_seed.dart from\n'
      '-- $manifestPath\n'
      '-- Portion policy: ${manifest['portionPolicyVersion']}.\n'
      '-- Curated by: ${mapping['curatedBy']} at ${mapping['curatedAt']}\n'
      '--\n'
      '-- Every row is verification_status = needs_review and reviewed_by =\n'
      '-- null. Curating the mapping is not reviewing the output.\n'
      '-- Prerequisite migration: 20260818220000_food_catalog_portion_references.sql\n';

  final foodsSql = StringBuffer(header);
  final aliasSql = StringBuffer(header);
  final portionSql = StringBuffer(header);
  final recordSql = StringBuffer(header);
  final publishSql = StringBuffer(header);

  var written = 0;
  var skipped = 0;
  var withPortions = 0;
  var portionRows = 0;

  for (final food in foods) {
    final slug = food['foodSlug'] as String;
    final group = bySlug[slug];
    if (group == null) {
      stderr.writeln(
        'No manifest rows for "$slug"; mapping and manifest drift',
      );
      exit(1);
    }
    final regular = group.firstWhere((r) => r['size_class'] == 'regular');
    final nutrition = regular['nutrition_per_100g'] as Map<String, dynamic>?;
    final resolved = group
        .where((r) => r['grams'] != null)
        .toList(growable: false);

    if (nutrition == null) {
      // No published composition: foods.calories/protein/carbs/fat are all
      // NOT NULL, so there is nothing honest to write.
      skipped++;
      foodsSql
        ..writeln('-- ${'-' * 74}')
        ..writeln('-- ${food['pilotName']}  (slug: $slug)')
        ..writeln('-- SKIPPED — no published per-100 g composition.')
        ..writeln(_wrap(regular['blocked_reason'] as String? ?? ''))
        ..writeln();
      continue;
    }
    written++;
    if (resolved.isNotEmpty) withPortions++;

    final metadata = <String, dynamic>{
      'batchId': batchId,
      // The foods row carries the status of its COMPOSITION, which is what
      // this row asserts. Writing "blocked" here would contradict the insert:
      // only the portion was blocked, and that is recorded separately.
      'verificationStatus': 'needs_review',
      'portionStatus': resolved.isEmpty ? 'none' : 'needs_review',
      'portionBasis': regular['portion_basis'],
      'sourceName': regular['source_name'],
      'sourceRecordId': regular['source_record_id'],
      'sourceUrl': regular['source_url'],
      'sourceRelease': regular['source_release'],
      'sourcePageOrTable': regular['source_page_or_table'],
      'retrievedAt': regular['retrieved_at'],
      'nutritionSource': regular['nutrition_source'],
      'nutritionSourceId': regular['nutrition_source_id'],
      'nutritionBasis': nutrition['basis'],
      'curatedBy': mapping['curatedBy'],
      'reviewedBy': null,
      'reviewedAt': null,
      'transformationNotes': regular['transformation_notes'],
      'hasPublishedPortion': resolved.isNotEmpty,
      if (resolved.isEmpty) 'noPortionReason': regular['blocked_reason'],
    };

    foodsSql
      ..writeln('-- ${'-' * 74}')
      ..writeln('-- ${food['pilotName']}  (slug: $slug)')
      ..writeln(
        resolved.isEmpty
            ? '-- No published portion. Composition is published and verified;\n'
                  '-- the app asks the user for the amount.'
            : '-- ${resolved.length} published portion row(s).',
      )
      ..writeln(
        'insert into public.foods (canonical_name, locale, source, '
        'source_food_id, calories_per_100g, protein_per_100g, '
        'carbs_per_100g, fat_per_100g, metadata)',
      )
      ..writeln(
        'values (${_q(regular['canonical_name_tr'] ?? food['pilotName'])}, '
        "'tr-TR', ${_q(source)}, ${_q(slug)}, "
        '${_n(nutrition['calories'])}, ${_n(nutrition['protein'])}, '
        '${_n(nutrition['carbs'])}, ${_n(nutrition['fat'])}, '
        '${_q(jsonEncode(metadata))}::jsonb)',
      )
      ..writeln('on conflict (source, source_food_id) do update set')
      ..writeln('  canonical_name = excluded.canonical_name,')
      ..writeln('  calories_per_100g = excluded.calories_per_100g,')
      ..writeln('  protein_per_100g = excluded.protein_per_100g,')
      ..writeln('  carbs_per_100g = excluded.carbs_per_100g,')
      ..writeln('  fat_per_100g = excluded.fat_per_100g,')
      ..writeln('  metadata = excluded.metadata;')
      ..writeln();

    final aliases = food['aliases'] as Map<String, dynamic>;
    for (final locale in aliases.keys) {
      for (final entry
          in (aliases[locale] as List).cast<Map<String, dynamic>>()) {
        aliasSql.writeln(
          'insert into public.food_aliases (food_id, alias, locale, priority) '
          'select id, ${_q(entry['alias'])}, ${_q(locale)}, '
          '${entry['priority']} from public.foods '
          'where source = ${_q(source)} and source_food_id = ${_q(slug)} '
          'on conflict (alias, locale, food_id) do update set '
          'priority = excluded.priority;',
        );
      }
    }

    for (final row in resolved) {
      portionRows++;
      final size = row['size_class'] as String;
      final isDefault = size == 'regular';
      portionSql
        ..writeln(
          'insert into public.food_portions (food_id, label, grams, locale, '
          'is_default, size_class, household_measure, reference_image_path, '
          'visual_status)',
        )
        ..writeln(
          'select id, ${_q(_label(size))}, ${_g(row['grams'] as num)}, '
          "'tr-TR', $isDefault, ${_q(size)}, "
          '${_q(row['household_measure'])}, null, \'missing\' '
          'from public.foods where source = ${_q(source)} '
          'and source_food_id = ${_q(slug)}',
        )
        ..writeln('on conflict (food_id, label, locale) do update set')
        ..writeln('  grams = excluded.grams,')
        ..writeln('  is_default = excluded.is_default,')
        ..writeln('  size_class = excluded.size_class,')
        ..writeln('  household_measure = excluded.household_measure;')
        ..writeln('--   intended image: ${row['image_path']}');

      publishSql.writeln(
        'update public.food_portions p set reference_image_path = '
        '${_q(row['image_path'])}, visual_status = \'reviewed\', '
        'visual_source = :image_source, visual_license = :image_license, '
        'visual_attribution = :attribution, reviewed_at = now() '
        'from public.foods f where p.food_id = f.id and '
        'f.source = ${_q(source)} and f.source_food_id = ${_q(slug)} '
        "and p.locale = 'tr-TR' and p.size_class = ${_q(size)};",
      );
    }
    portionSql.writeln();

    recordSql.writeln(
      'insert into public.catalog_source_records (batch_id, source_food_id, '
      'payload, validation_errors) select b.id, ${_q(slug)}, '
      '${_q(jsonEncode(food))}::jsonb, '
      '${_q(jsonEncode(resolved.isEmpty ? [
              {'code': 'NO_PUBLISHED_PORTION', 'reason': regular['blocked_reason'], 'searchedSources': regular['searched_sources']},
            ] : []))}::jsonb '
      'from public.catalog_import_batches b where b.source = ${_q(source)} '
      'and b.source_release = ${_q(batchId)} '
      'on conflict (batch_id, source_food_id) do update set '
      'payload = excluded.payload, '
      'validation_errors = excluded.validation_errors;',
    );
  }

  final checksum = _sha256Hex(File(manifestPath).readAsBytesSync());
  final batchSql = StringBuffer(header)
    ..writeln(
      'insert into public.catalog_import_batches (source, source_release, '
      'status, record_count, checksum, metadata)',
    )
    ..writeln(
      'values (${_q(source)}, ${_q(batchId)}, \'staged\', $written, '
      '${_q(checksum)}, ${_q(jsonEncode({'portionPolicyVersion': manifest['portionPolicyVersion'], 'selectionRulesVersion': mapping['selectionRulesVersion'], 'curatedBy': mapping['curatedBy'], 'counts': manifest['counts']}))}::jsonb)',
    )
    ..writeln(
      'on conflict (source, source_release, checksum) do update set '
      'record_count = excluded.record_count, metadata = excluded.metadata;',
    );

  final deactivateSql = StringBuffer(header)
    ..writeln(
      '-- The curated-demo records carry unsourced macros and own aliases the\n'
      '-- sourced records also claim. food_aliases is unique on\n'
      '-- (alias, locale, food_id), so both would answer the same search.\n'
      '-- Deactivated rather than deleted: aliases and portions cascade on\n'
      '-- delete, is_active is already the search filter, and historical\n'
      '-- meal_items.food_id references must survive.',
    )
    ..writeln(
      "update public.foods set is_active = false, updated_at = now()\n"
      " where source = 'curated-demo'\n"
      "   and source_food_id in ('egg-boiled', 'white-cheese-full-fat', "
      "'simit');",
    );

  Directory(outDir).createSync(recursive: true);
  final files = <String, String>{
    '000_batch.sql': batchSql.toString(),
    '010_foods.sql': foodsSql.toString(),
    '020_aliases.sql': aliasSql.toString(),
    '030_portions.sql': portionSql.toString(),
    '050_source_records.sql': recordSql.toString(),
    '090_deactivate_curated_demo.sql': deactivateSql.toString(),
  };
  files.forEach((name, body) => File('$outDir/$name').writeAsStringSync(body));

  // Deliberately not .sql: applying this before a human has reviewed and
  // rendered the images would mark them published with no reviewer.
  File('$outDir/900_publish_images.sql.txt').writeAsStringSync(
    '$header-- DO NOT APPLY. Run only after image QA sign-off, substituting\n'
    '-- real reviewer, source, license and attribution literals.\n'
    '${publishSql.toString().substring(header.length)}',
  );

  File('$outDir/_apply.sql').writeAsStringSync(
    '$header-- psql "\$DB_URL" -v ON_ERROR_STOP=1 -f _apply.sql\n'
    '${files.keys.map((f) => '\\ir $f').join('\n')}\n',
  );

  stdout
    ..writeln('foods written        $written')
    ..writeln('  with portions      $withPortions')
    ..writeln('  without portions   ${written - withPortions}')
    ..writeln('skipped (no macros)  $skipped')
    ..writeln('portion rows         $portionRows')
    ..writeln('-> $outDir');
}

String _label(String size) => switch (size) {
  'small' => 'az',
  'regular' => '1 porsiyon',
  'large' => 'fazla',
  _ => size,
};

String _q(Object? value) =>
    value == null ? 'null' : "'${value.toString().replaceAll("'", "''")}'";

String _n(Object? value) => value == null ? 'null' : '$value';

String _g(num grams) =>
    grams == grams.roundToDouble() ? '${grams.round()}' : '$grams';

String _wrap(String text) => text
    .split(RegExp(r'\s+'))
    .fold<List<String>>(<String>['--'], (lines, word) {
      if ('${lines.last} $word'.length > 92) {
        lines.add('-- $word');
      } else {
        lines[lines.length - 1] = '${lines.last} $word';
      }
      return lines;
    })
    .join('\n');

String? _arg(List<String> args, String name) {
  final i = args.indexOf(name);
  if (i == -1 || i + 1 >= args.length) return null;
  return args[i + 1];
}

String _sha256Hex(List<int> bytes) => sha256OfBytes(bytes);
