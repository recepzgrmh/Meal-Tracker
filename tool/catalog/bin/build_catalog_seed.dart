// Emits a REVIEWABLE SQL seed for the pilot portion references.
//
//   dart run tool/catalog/bin/build_catalog_seed.dart
//
// The file it writes is not applied by this script and is not part of the
// migration chain. Nothing here is invented: every value is copied out of
// tool/catalog/out/pilot_portion_manifest.json, which is itself built from
// hashed source snapshots. Blocked foods are emitted as comments so the gap
// stays visible in the SQL a reviewer reads.
import 'dart:convert';
import 'dart:io';

const _out = 'supabase/seed/pilot_portion_references.sql';

void main() {
  final manifest =
      jsonDecode(
            File(
              'tool/catalog/out/pilot_portion_manifest.json',
            ).readAsStringSync(),
          )
          as Map<String, dynamic>;
  final mapping =
      jsonDecode(
            File(
              'tool/catalog/data/pilot_food_mapping.json',
            ).readAsStringSync(),
          )
          as Map<String, dynamic>;

  final portions = (manifest['portions'] as List<dynamic>)
      .cast<Map<String, dynamic>>();
  final bySlug = <String, List<Map<String, dynamic>>>{};
  for (final row in portions) {
    bySlug.putIfAbsent(row['food_slug'] as String, () => []).add(row);
  }

  final buffer = StringBuffer()
    ..writeln(
      '-- Pilot portion references — REVIEW REQUIRED, DO NOT APPLY UNREVIEWED.',
    )
    ..writeln('--')
    ..writeln('-- Generated by tool/catalog/bin/build_catalog_seed.dart from')
    ..writeln(
      '-- tool/catalog/out/pilot_portion_manifest.json (batch ${manifest['batchId']}).',
    )
    ..writeln('-- Portion policy: ${manifest['portionPolicyVersion']}.')
    ..writeln('--')
    ..writeln(
      '-- Prerequisite migration: 20260818220000_food_catalog_portion_references.sql',
    )
    ..writeln(
      '-- Every row below is verification_status = needs_review. No row may be',
    )
    ..writeln(
      '-- promoted to visual_status reviewed/published without a named human.',
    )
    ..writeln();

  for (final food
      in (mapping['foods'] as List<dynamic>).cast<Map<String, dynamic>>()) {
    final slug = food['foodSlug'] as String;
    final rows = bySlug[slug]!;
    buffer.writeln('-- ${'-' * 74}');
    buffer.writeln('-- ${food['pilotName']}  (slug: $slug)');

    if (food['status'] == 'blocked') {
      buffer
        ..writeln('-- BLOCKED — no row is written.')
        ..writeln(_wrapComment(food['blockedReason'] as String))
        ..writeln(
          '-- Resolution: ${_wrapComment(food['resolutionPath'] as String).substring(3)}',
        )
        ..writeln();
      continue;
    }

    final regular = rows.firstWhere((row) => row['size_class'] == 'regular');
    final nutrition = regular['nutrition_per_100g'] as Map<String, dynamic>;
    final sourceId = _sourceFoodId(regular);
    final metadata = jsonEncode({
      'batchId': manifest['batchId'],
      'verificationStatus': regular['verification_status'],
      'sourceName': regular['source_name'],
      'sourceRecordId': regular['source_record_id'],
      'sourceUrl': regular['source_url'],
      'sourceRelease': regular['source_release'],
      'sourcePageOrTable': regular['source_page_or_table'],
      'retrievedAt': regular['retrieved_at'],
      'nutritionSource': regular['nutrition_source'],
      'nutritionSourceId': regular['nutrition_source_id'],
      'nutritionSourceUrl': regular['nutrition_source_url'],
      'nutritionBasis': nutrition['basis'],
      'reviewedBy': regular['reviewed_by'],
      'reviewedAt': regular['reviewed_at'],
      'transformationNotes': regular['transformation_notes'],
      'sourceConflicts': regular['source_conflicts'],
    });

    if (food['aliasPolicyNote'] != null) {
      buffer.writeln(_wrapComment(food['aliasPolicyNote'] as String));
    }
    for (final conflict
        in (regular['source_conflicts'] as List<dynamic>).cast<String>()) {
      buffer.writeln(_wrapComment('CONFLICT: $conflict'));
    }

    buffer
      ..writeln('insert into public.foods (')
      ..writeln('  canonical_name, locale, source, source_food_id,')
      ..writeln(
        '  calories_per_100g, protein_per_100g, carbs_per_100g, fat_per_100g, metadata',
      )
      ..writeln(') values (')
      ..writeln(
        "  ${_q(regular['canonical_name_tr'])}, 'tr-TR', 'tuber-turkomp-pilot', ${_q(sourceId)},",
      )
      ..writeln(
        '  ${nutrition['calories']}, ${nutrition['protein']}, '
        '${nutrition['carbs']}, ${nutrition['fat']}, ${_q(metadata)}::jsonb',
      )
      ..writeln(')')
      ..writeln('on conflict (source, source_food_id) do update set')
      ..writeln('  canonical_name = excluded.canonical_name,')
      ..writeln('  calories_per_100g = excluded.calories_per_100g,')
      ..writeln('  protein_per_100g = excluded.protein_per_100g,')
      ..writeln('  carbs_per_100g = excluded.carbs_per_100g,')
      ..writeln('  fat_per_100g = excluded.fat_per_100g,')
      ..writeln('  metadata = excluded.metadata;')
      ..writeln();

    final aliases = (food['aliases'] as Map<String, dynamic>?) ?? const {};
    for (final entry in aliases.entries) {
      for (final raw
          in (entry.value as List<dynamic>).cast<Map<String, dynamic>>()) {
        if (raw['conflict'] != null) {
          buffer.writeln(
            _wrapComment('ALIAS ${raw['alias']}: ${raw['conflict']}'),
          );
        }
        buffer
          ..writeln(
            'insert into public.food_aliases (food_id, alias, locale, priority)',
          )
          ..writeln(
            'select id, ${_q(raw['alias'])}, ${_q(entry.key)}, ${raw['priority']}',
          )
          ..writeln(
            "from public.foods where source = 'tuber-turkomp-pilot' "
            'and source_food_id = ${_q(sourceId)}',
          )
          ..writeln(
            'on conflict (alias, locale, food_id) do update set '
            'priority = excluded.priority;',
          );
      }
    }
    buffer.writeln();

    for (final row in rows) {
      buffer
        ..writeln('insert into public.food_portions (')
        ..writeln('  food_id, label, grams, locale, is_default, size_class,')
        ..writeln('  household_measure, reference_image_path, visual_status')
        ..writeln(')')
        ..writeln(
          'select id, ${_q(_portionLabel(row))}, ${_g(row['grams'] as num)}, '
          "'tr-TR', ${row['size_class'] == 'regular'}, ${_q(row['size_class'])},",
        )
        ..writeln('  ${_q(row['household_measure'])}, null, \'missing\'')
        ..writeln(
          "from public.foods where source = 'tuber-turkomp-pilot' "
          'and source_food_id = ${_q(sourceId)}',
        )
        ..writeln('on conflict (food_id, label, locale) do update set')
        ..writeln('  grams = excluded.grams,')
        ..writeln('  is_default = excluded.is_default,')
        ..writeln('  size_class = excluded.size_class,')
        ..writeln('  household_measure = excluded.household_measure;')
        ..writeln(
          '-- reference image (upload first, then run the publish block below):',
        )
        ..writeln('--   ${row['image_path']}');
    }
    buffer.writeln();
  }

  buffer
    ..writeln('-- ${'=' * 74}')
    ..writeln('-- PUBLISH BLOCK — run only after the image exists in the')
    ..writeln(
      "-- 'food-portion-references' bucket AND a named reviewer signed the QA",
    )
    ..writeln(
      '-- checklist in docs/PORTION_REFERENCE_PILOT.md. Fill in the reviewer,',
    )
    ..writeln(
      '-- source, license and attribution literals; do not leave them null.',
    )
    ..writeln('/*');
  for (final row in portions) {
    if (row['image_path'] == null) continue;
    final sourceId = _sourceFoodId(row);
    buffer
      ..writeln('update public.food_portions p set')
      ..writeln('  reference_image_path = ${_q(row['image_path'])},')
      ..writeln("  visual_status = 'reviewed',")
      ..writeln('  visual_source = :image_source,')
      ..writeln('  visual_license = :image_license,')
      ..writeln('  visual_attribution = :attribution,')
      ..writeln('  reviewed_at = now()')
      ..writeln('from public.foods f')
      ..writeln("where p.food_id = f.id and f.source = 'tuber-turkomp-pilot'")
      ..writeln('  and f.source_food_id = ${_q(sourceId)}')
      ..writeln(
        "  and p.locale = 'tr-TR' and p.size_class = ${_q(row['size_class'])};",
      );
  }
  buffer.writeln('*/');

  File(_out).writeAsStringSync(buffer.toString());
  stdout.writeln('wrote $_out');
}

String _sourceFoodId(Map<String, dynamic> row) => row['food_slug'] as String;

String _portionLabel(Map<String, dynamic> row) => switch (row['size_class']) {
  'small' => 'az',
  'regular' => '1 porsiyon',
  _ => 'fazla',
};

String _q(Object? value) =>
    value == null ? 'null' : "'${value.toString().replaceAll("'", "''")}'";

String _g(num grams) => grams == grams.roundToDouble()
    ? grams.round().toString()
    : grams.toString();

String _wrapComment(String text) {
  final words = text.split(' ');
  final lines = <String>[];
  var current = StringBuffer('--');
  for (final word in words) {
    if (current.length + word.length + 1 > 96) {
      lines.add(current.toString());
      current = StringBuffer('--');
    }
    current.write(' $word');
  }
  lines.add(current.toString());
  return lines.join('\n');
}
